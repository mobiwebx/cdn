    /**
    * Shows the context menu at the given coordinates, adjusting for viewport boundaries and padding.
    * @param {number} clientX - The clientX coordinate where the menu should ideally appear.
    * @param {number} clientY - The clientY coordinate where the menu should ideally appear.
    * @param {Element} triggerElement - The DOM element that caused the menu to show (e.g., the highlight itself or its parent).
    * @param {string|null} [activeColor=null] - The color name to set as active in the menu.
    * @param {string|null} [activeUnderline=null] - The underline style to set as active in the menu.
    * @param {number} [padding=10] - The minimum padding from the viewport edges.
    */
    show(clientX, clientY, triggerElement, activeColor = null, activeUnderline = null, padding = 10) {
        this.#logger.debug(`Attempting to show menu at clientX: ${clientX}, clientY: ${clientY}`);

        // Fallback to recalculate dimensions if initial calculation failed (e.g., if elements weren't ready)
        if (this.#menuWidth === 0 || this.#menuHeight === 0) {
            this.#logger.warn('Recalculating menu dimensions in show() as they were zero.');
            this.#calculateMenuDimensions();
        }

        this.#setActiveColor(activeColor);
        this.#setActiveUnderline(activeUnderline);

        const viewportWidth = document.documentElement.clientWidth;
        const viewportHeight = document.documentElement.clientHeight;

        let finalLeft = clientX;
        let finalTop = clientY;

        // Adjust left position
        if (clientX + this.#menuWidth + padding > viewportWidth) {
            finalLeft = viewportWidth - this.#menuWidth - padding;
        }
        if (finalLeft < padding) {
            finalLeft = padding;
        }

        // Adjust top position
        if (clientY + this.#menuHeight + padding > viewportHeight) {
            finalTop = viewportHeight - this.#menuHeight - padding;
        }
        if (finalTop < padding) {
            finalTop = padding;
        }

        this.style.left = `${finalLeft}px`;
        this.style.top = `${finalTop}px`;

        // NEW: Find and listen to scrollable containers
        this.#addScrollAndResizeListeners(triggerElement);

        this.style.visibility = 'visible';
        this.style.display = 'block'; // Ensure it's fully visible after positioning

        document.addEventListener('pointerdown', this.#boundHandleGlobalPointerDown);
        this.#logger.debug(`Context menu shown at Clicks(X=${clientX}, Y=${clientY}) -> Final(T=${finalTop.toFixed(1)}px, L=${finalLeft.toFixed(1)}px)`);
    }

    /**
     * Hides the context menu.
     * @fires menu-closed - Dispatched when the menu is hidden.
     * @returns {void}
     */
    hide() {
        if (this.style.display === 'none') { // Already hidden, prevent redundant operations
            return;
        }
        this.style.display = 'none';
        document.removeEventListener('pointerdown', this.#boundHandleGlobalPointerDown);
        this.#removeScrollAndResizeListeners(); // NEW: Remove listeners when hiding
        this.dispatchEvent(new CustomEvent('menu-closed'));
        this.#logger.info("Context menu hidden.");
    }

    /**
     * Helper method to synchronize boolean properties and attributes.
     * @param {string} propName - The name of the property (e.g., 'checked', 'disabled').
     * @param {string} attrName - The name of the corresponding attribute (e.g., 'checked', 'disabled').
     * @param {any} value - The new value to set.
     * @returns {boolean} True if the property actually changed, false otherwise.
     */
    #syncBooleanProperty(propName, attrName, value) {
        if (typeof value !== 'boolean') {
            this.#logger.warn(`Invalid value provided for ${propName}. Expected a boolean.`);
        }

        const privatePropName = `_${propName}`;
        const booleanValue = Boolean(value);

        // 1. Change Detection
        if (this[privatePropName] === booleanValue) {
            return false;
        }

        // 2. Update Internal State
        this[privatePropName] = booleanValue;

        // 3. Reflect to Attribute
        if (booleanValue) {
            this.setAttribute(attrName, '');
        } else {
            this.removeAttribute(attrName);
        }
        return true;
    }

    /**
     * Generates a <style> tag with CSS variables for the color definitions
     * and inserts/updates it in the shadow DOM. It also defines hover styles
     * for color swatches based on these definitions.
     * @private
     * @returns {void}
     */
    #insertDynamicColorStyles() {
        const styleTag = this.shadowRoot.getElementById('highlight-dynamic-color-styles');
        if (!styleTag) {
            this.#logger.error('Dynamic color style tag not found.');
            return;
        }

        let cssContent = ':host {\n';
        this.#colorDefinitions.forEach(colorInfo => {
            // Define CSS variables for base and active colors
            cssContent += `  --highlight-color-${colorInfo.name}-base: ${colorInfo.baseCssColor};\n`;
            cssContent += `  --highlight-color-${colorInfo.name}-hover: ${colorInfo.hoverCssColor};\n`;
            cssContent += `  --highlight-color-${colorInfo.name}-active: ${colorInfo.activeCssColor};\n`;
        });
        cssContent += '}\n\n';

        this.#colorDefinitions.forEach(colorInfo => {
            cssContent += `.annotatable-content-context-menu .color-swatch[data-color-name="${colorInfo.name}"] {\n`;
            cssContent += `  background-color: var(--highlight-color-${colorInfo.name}-base);\n`;
            cssContent += `}\n`;
        });

        this.#colorDefinitions.forEach(colorInfo => {
            cssContent += `.annotatable-content-context-menu .color-swatch[data-color-name="${colorInfo.name}"]:hover {\n`;
            cssContent += `  background-color: var(--highlight-color-${colorInfo.name}-hover);\n`;
            cssContent += `}\n`;
        });

        this.#colorDefinitions.forEach(colorInfo => {
            cssContent += `.annotatable-content-context-menu .add-note-icon[data-color-name="${colorInfo.name}"]:hover .note-icon-fill {\n`;
            cssContent += `  fill: var(--highlight-color-${colorInfo.name}-hover);\n`;
            cssContent += `}\n`;
        });

        styleTag.textContent = cssContent;
        this.#logger.debug("Dynamic color styles updated with colorDefinition-based hover.");
    }

    /**
     * Sets the active color swatch in the menu.
     * @private
     * @param {string|null} color - The color name to set as active. If null, no color will be active.
     * @returns {void}
     */
    #setActiveColor(color) {
        if (!this.#menuContainerElement) return;

        this.#activeColor = color;
        // Update active color swatch
        this.#menuContainerElement.querySelectorAll('.color-swatch').forEach(swatch => {
            if (swatch.dataset.colorName === color) {
                swatch.classList.add('active');
            } else {
                swatch.classList.remove('active');
            }
        });

        this.#menuContainerElement.querySelectorAll('.add-note-icon').forEach(icon => {
            if (icon.dataset.colorName === (color || this.#lastUsedColor)) {
                icon.classList.add('active');
            } else {
                icon.classList.remove('active');
            }
        })
    }

