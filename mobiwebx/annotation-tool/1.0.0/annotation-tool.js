        this._notesCollapsibleDisabled = this.hasAttribute('notes-collapsible-disabled');
        this._notesCollapsed = this.hasAttribute('notes-collapsed');
        this._autoHighlight = this.hasAttribute('auto-highlight');

        // Ensure notesCollapsed is false if not collapsible (e.g., if someone adds 'notes-collapsed'
        // but also 'notes-collapsible-disabled')
