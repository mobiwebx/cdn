    /**
     * Handles the `click` event to detect clicks on existing highlights.
     *
     * This function is responsible for determining if a click landed on an already
     * existing text highlight. If it did, it manages the selection state of highlights
     * and displays the context menu relevant to the clicked highlight.
     *
     * @param {MouseEvent} event - The click event.
     * @private
     */
    #handleClick(event) {
        if (!this.#isApiSupported) {
            this.#logger.warn("API not supported.");
            return;
        }
        if (!this.#annotationManager) {
            this.#logger.warn("Annotation manager not initialized.");
            return;
        }
        this.#logger.debug("_handleClick triggered.");

        // Check if the click originated from inside the context menu itself.
        // If so, we don't want to process it as a document click on a highlight.
        // if (this.#contextMenuInstance && event.composedPath().includes(this.#contextMenuInstance)) { // Original logic for context menu in shadow dom
        if (this.#contextMenuInstance && this.#contextMenuInstance.contains(event.target)) { // Adjusted for singleton in light DOM
            this.#logger.debug('Click originated from inside the context menu');
            return;
        }

        const selection = window.getSelection();

        // Only process click if there's no active text selection (meaning the selection is collapsed
        // to a single point, like a caret, or there's no selection at all).
        // This prevents accidental highlight clicks when the user is trying to select text.
        if (selection && selection.isCollapsed && event.target) {
            this.#logger.debug("Click is on a highlight area, checking for existing highlights...");

            // Use the shared utility function to precisely determine if a highlight was clicked.
            const clickedHighlightId = this.#getHighlightIdAtPoint(event.clientX, event.clientY);

            // Get the currently selected highlight's ID (if any).
            const currentlySelectedId = this.#annotationManager.getIdInState(AnnotationManager.STATE_TYPES.SELECTED);

            if (clickedHighlightId) {
                // A highlight was clicked.
                const highlightEntry = this.#annotationManager.getHighlight(clickedHighlightId);
                if (!highlightEntry || !highlightEntry.range) {
                    // Defensive check: if annotationManager returned an ID but no valid entry/range
                    this.#logger.warn(`Clicked ID ${clickedHighlightId} found, but no valid entry or range.`);
                    return;
                }

                this.#logger.debug(`Clicked on existing highlight ID: ${clickedHighlightId}`);

                if (currentlySelectedId !== clickedHighlightId) {
                    // If a *different* highlight was already selected, deselect it.
                    if (currentlySelectedId) {
                        this.#annotationManager.setState(currentlySelectedId, { [AnnotationManager.STATE_TYPES.SELECTED]: false });
                    }
                    // Select the newly clicked highlight.
                    this.#annotationManager.setState(clickedHighlightId, { [AnnotationManager.STATE_TYPES.SELECTED]: true });
                }

                // Show the context menu relevant to the clicked highlight.
                // We pass the highlight's range, the event target, and specific properties needed by the menu.
                this.#showContextMenu(
                    highlightEntry.range,
                    event.target,
                    highlightEntry.colorName,
                    highlightEntry.underline
                );
            } else {
                // Click did not land on an existing highlight.
                this.#logger.debug("Click did not land on an existing highlight.");
                if (currentlySelectedId) { // Only deselect if something was selected
                    this.#annotationManager.setState(currentlySelectedId, { [AnnotationManager.STATE_TYPES.SELECTED]: false });
                }
                // And potentially hide the context menu if it's open:
                if (this.#contextMenuInstance) {
                    this.#contextMenuInstance.hide();
                }
            }
        } else if (selection && !selection.isCollapsed) {
            this.#logger.debug("Selection is active, not processing as a simple click on highlight.");
            // Do not hide context menu or deselect if user is making a selection.
        } else {
            this.#logger.debug("No selection or invalid target for click handling.");
            // If there's no selection and no target, it's likely a click on whitespace.
            // In this case, hide the context menu if it's open and deselect any highlight.
            const currentlySelectedId = this.#annotationManager?.getIdInState(AnnotationManager.STATE_TYPES.SELECTED);
            if (currentlySelectedId) {
                this.#annotationManager.setState(currentlySelectedId, { [AnnotationManager.STATE_TYPES.SELECTED]: false });
            }
            if (this.#contextMenuInstance) {
                this.#contextMenuInstance.hide();
            }
        }
    }

