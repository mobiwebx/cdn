    /**
     * Shows the delete confirmation overlay for a specific note card.
     * Ensures only one confirmation is visible at a time and adjusts card height.
     * @param {string} highlightId - The ID of the highlight/note to be deleted.
     * @private
     */
    #showDeleteConfirmation(highlightId) {
        // If another confirmation is open, dismiss it first
        if (this.#currentNoteAwaitingDeletion && this.#currentNoteAwaitingDeletion !== highlightId) {
            this.#hideDeleteConfirmation(this.#currentNoteAwaitingDeletion);
            this.#logger.info(`Dismissing previous confirmation for ID: ${this.#currentNoteAwaitingDeletion}`);
        }

        const noteCard = this.shadowRoot.querySelector(`.note-card[data-highlight-id="${highlightId}"]`);
        if (noteCard) {
            const overlay = noteCard.querySelector('.confirmation-overlay');
            if (overlay) {
                overlay.classList.add('visible');
                this.#currentNoteAwaitingDeletion = highlightId; // Store the ID of the currently visible confirmation
                this.#logger.info(`Showing delete confirmation for note ID: ${highlightId}`);

                // Measure and adjust card height to fit the dialog
                requestAnimationFrame(() => {
                    const dialog = overlay.querySelector('.confirmation-dialog');
                    if (dialog) {
                        const dialogHeight = dialog.offsetHeight;
                        const cardHeight = noteCard.offsetHeight;
                        if (dialogHeight > cardHeight) {
                            noteCard.style.setProperty('--hn-card-min-height-for-dialog', `${dialogHeight}px`);
                            noteCard.classList.add('has-active-dialog');
                            this.#logger.info(`Adjusted card ${highlightId} min-height to ${dialogHeight}px to fit dialog.`);
                        }
                    }
                });
            }
        } else {
            this.#logger.warn(`Note card for highlight ID ${highlightId} not found when trying to show delete confirmation.`);
        }
    }

    /**
     * Hides the delete confirmation overlay for a specific note card.
     * Reverts card height adjustments.
     * @param {string} highlightId - The ID of the highlight/note for which to hide the confirmation.
     * @private
     */
    #hideDeleteConfirmation(highlightId) {
        const noteCard = this.shadowRoot.querySelector(`.note-card[data-highlight-id="${highlightId}"]`);
        if (noteCard) {
            const overlay = noteCard.querySelector('.confirmation-overlay');
            if (overlay) {
                overlay.classList.remove('visible');
                noteCard.classList.remove('has-active-dialog'); // Remove the class that sets min-height
                noteCard.style.removeProperty('--hn-card-min-height-for-dialog'); // Remove the inline style

                // Only clear #currentNoteAwaitingDeletion if this was the one being dismissed
                if (this.#currentNoteAwaitingDeletion === highlightId) {
                    this.#currentNoteAwaitingDeletion = null;
                }
                this.#logger.info(`Hiding delete confirmation for note ID: ${highlightId} and reverting card height.`);
            }
        }
    }

    /**
     * Handles the 'Confirm' button click in the delete confirmation dialog.
     * This method now receives the highlightId directly.
     * @param {string} highlightId - The ID of the highlight/note to be deleted.
     * @private
     */
    #handleConfirmDelete(highlightId) {
        // Ensure the confirmed ID matches the currently active confirmation
        if (this.#currentNoteAwaitingDeletion === highlightId && this.#annotationManager) {
            this.#logger.info(`Confirmed deletion for note ID: ${highlightId}. Attempting to delete note.`);
            const deleted = this.#annotationManager.deleteNote(highlightId);
            if (deleted) {
                this.#logger.info(`Note with ID ${highlightId} successfully deleted from manager.`);
            } else {
                this.#logger.warn(`Failed to delete note with ID ${highlightId} from manager.`);
            }
            // The handleNoteDeleted event will naturally remove the card and dismiss the overlay.
            // However, we call hide explicitly here to clear the #currentNoteAwaitingDeletion state immediately
            // and revert height changes.
            this.#hideDeleteConfirmation(highlightId);
        } else {
            this.#logger.warn(`Confirm delete called for ID ${highlightId}, but no active confirmation was for this ID (${this.#currentNoteAwaitingDeletion}).`);
            // If there's a mismatch, just hide the overlay for the requested ID if it exists.
            this.#hideDeleteConfirmation(highlightId);
        }
    }
