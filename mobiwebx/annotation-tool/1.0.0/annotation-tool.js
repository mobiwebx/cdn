    /**
    * Determines if the current selection is entirely within the slotted light DOM.
    * @param {Selection} [selection] - The selection to check. If null, the current window selection is used.
    * @returns {boolean} True if the selection is entirely within the slotted light DOM, false otherwise.
    */
    #isSelectionInSlot(selection = null) {
        if (!selection) {
            selection = window.getSelection();
        }
        const slot = this.shadowRoot.querySelector('slot');

        if (!selection || selection.rangeCount === 0) {
            return false;
        }

        // Get the ranges that compose the selection, traversing shadow boundaries
        const composedRanges = selection.getComposedRanges();

        if (composedRanges.length === 0) {
            this.#logger.info('No composed ranges, selection might be empty or problematic.');
            return false;
        }

        let isSelectionInSlot = true; // Assume true, then prove false

        // Get the nodes that are actually assigned to deep-comp's slot
        const assignedNodes = slot.assignedNodes({ flatten: true });
        const assignedElements = assignedNodes.filter(node => node.nodeType === Node.ELEMENT_NODE);
        // Also get the text nodes if they can be directly slotted (e.g., if a text node itself is slotted directly)
        const assignedTextNodes = assignedNodes.filter(node => node.nodeType === Node.TEXT_NODE);


        // Helper to check if a node is part of the assigned slotted content
        const isNodeInSlottedContent = (node) => {
            if (!node) return false;

            // Check if the node itself is one of the directly assigned text nodes
            if (node.nodeType === Node.TEXT_NODE && assignedTextNodes.includes(node)) {
                return true;
            }

            // For element nodes, check if the element is an an assigned element or contained within one
            let currentElement = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;

            while (currentElement) {
                if (assignedElements.includes(currentElement)) {
                    return true;
                }
                // Stop if we hit a shadow root boundary that isn't our own
                if (currentElement.shadowRoot && currentElement.shadowRoot !== this.shadowRoot) {
                    return false;
                }
                currentElement = currentElement.parentElement;
            }
            return false;
        };

        // Iterate through each composed range to verify its bounds
        for (const range of composedRanges) {
            // Start and end containers of the current range
            const startContainer = range.startContainer;
            const endContainer = range.endContainer;

            // A key check: if the range is *within* deep-comp's shadow DOM,
            // and its *root* is deep-comp's shadowRoot, then it's not slotted content.
            if (range.startContainer.getRootNode() === this.shadowRoot || range.endContainer.getRootNode() === this.shadowRoot) {
                // If *any part* of the composed range is within *this component's* shadow DOM
                // (and not the slotted content), then it's not entirely in the slotted light DOM.
                // We need to ensure that the start/end containers are not 'Deep:' text or its parent div.
                const isStartInsideDeepCompInternal = (startContainer.nodeType === Node.TEXT_NODE && startContainer.textContent.includes('Deep:')) ||
                    (startContainer.nodeType === Node.ELEMENT_NODE && startContainer.shadowRoot === this.shadowRoot && startContainer.contains(slot)); // Check if it's the internal div or its content
                const isEndInsideDeepCompInternal = (endContainer.nodeType === Node.TEXT_NODE && endContainer.textContent.includes('Deep:')) ||
                    (endContainer.nodeType === Node.ELEMENT_NODE && endContainer.shadowRoot === this.shadowRoot && endContainer.contains(slot));

                if (isStartInsideDeepCompInternal || isEndInsideDeepCompInternal) {
                    isSelectionInSlot = false;
                    break; // Exit loop, found an internal selection
                }
            }

            // Also check if the start/end of the range are NOT within the assigned slotted content
            if (!isNodeInSlottedContent(startContainer) || !isNodeInSlottedContent(endContainer)) {
                isSelectionInSlot = false;
                break; // Exit loop, selection part is outside slotted content
            }
        }

        return isSelectionInSlot;
    }

    /**
     * Gets the ID of the highlight with the highest priority (shortest length) at a given point (x, y).
     * If multiple highlights overlap the point, the one with the shortest accumulated width of its client rectangles is chosen.
     *
     * @param {number} x - The X-coordinate of the point.
     * @param {number} y - The Y-coordinate of the point.
     * @returns {string | null} The ID of the highest-priority highlight at the point, or `null` if no highlight is found.
     */
    #getHighlightIdAtPoint(x, y) {
        if (!this.#annotationManager) {
            return null; // Return null if no annotation manager
        }

        let bestHighlightId = null;
        let minLength = Infinity; // Initialize with a very large number

        for (const id of this.#annotationManager.keys()) {
            const entry = this.#annotationManager.getHighlight(id);
            if (entry && entry.range) {
                try {
                    // Calculate highlightLength once per highlight entry, outside the inner rects loop
                    
                    const rects = entry.range.getClientRects();
                    const highlightLength = Array.from(rects).reduce((sum, r) => sum + r.width, 0);

                    for (const rect of rects) {
                        // Check if the point (x, y) falls within the current rectangle
                        if (x >= rect.left &&
                            x <= rect.right &&
                            y >= rect.top &&
                            y <= rect.bottom) {

                            // If this highlight is shorter than the current minimum, or if it's the first one found
                            if (highlightLength < minLength) {
                                minLength = highlightLength;
                                bestHighlightId = id;
                            }

                            // Found an overlapping rect for this highlight, no need to check other rects for this same highlight.
                            // We move to the next highlight ID.
                            break;
                        }
                    }
                } catch (e) {
                    // This can happen if the range is no longer in the document (e.g., content removed)
                    this.#logger.warn(`Error getting client rects for highlight ID ${id}: ${e.message}`);
                }
            }
        }

        return bestHighlightId; // Returns the ID of the shortest overlapping highlight, or null if none
    }
