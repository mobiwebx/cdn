    /**
     * Generates a unique path for a given DOM node (element or text node) relative to a container element.
     * The path is an array of child indices.
     * @private
     * @param {Node} node - The DOM node to get the path for.
     * @param {HTMLElement|ShadowRoot} containerElement - The root element from which the path is calculated.
     * @returns {number[]|null} The path as an array of numbers, or `null` if the node is not within the container.
     */
    #getNodePath(node, containerElement) {
        if (!node || !containerElement || !containerElement.contains(node)) {
            return null;
        }
        const path = [];
        let currentNode = node;
        while (currentNode && currentNode !== containerElement) {
            let index = 0;
            let sibling = currentNode.previousSibling;
            while (sibling) {
                index++;
                sibling = sibling.previousSibling;
            }
            path.unshift(index);
            currentNode = currentNode.parentNode;
        }
        return path;
    }

    /**
     * Reconstructs a DOM node (element or text node) from a given path (array of child indices)
     * relative to a container element.
     * @private
     * @param {number[]} path - The path as an array of numbers.
     * @param {HTMLElement|ShadowRoot} containerElement - The root element from which the node is reconstructed.
     * @returns {Node|null} The found DOM node or `null` if not found or path is invalid.
     */
    #getNodeFromPath(path, containerElement) {
        if (!path || !Array.isArray(path) || !containerElement) {
            return null;
        }
        let currentNode = containerElement;
        for (const index of path) {
            if (!currentNode || index >= currentNode.childNodes.length) {
                return null; // Path is invalid or node not found
            }
            currentNode = currentNode.childNodes[index];
        }
        return currentNode;
    }

    /**
     * Serializes a Range object into a plain object containing its path-based representation.
     * It finds the nearest parent with the `data-highlight-root` attribute to serve as the root container.
     * If no such parent is found, `document.body` is used as the root container.
     * @private
     * @param {Range} range - The Range object to serialize.
     * @returns {object|null} A serializable object with start/end container paths, offsets, and rootContainerKey, or null if the range is invalid.
     */
    #serializeRange(range) {
        if (!range || !range.startContainer || !range.endContainer) {
            this.#logger.error("Attempted to serialize an invalid Range object.");
            return null;
        }

        // Determine the root container for serialization
        // We start from the common ancestor and look upwards
        const commonAncestor = range.commonAncestorContainer;
        let effectiveRootContainer = commonAncestor.nodeType === Node.ELEMENT_NODE ?
            commonAncestor.closest('[data-highlight-root]') :
            commonAncestor.parentElement?.closest('[data-highlight-root]');

        // Fallback to document.body if no data-highlight-root ancestor is found
        if (!effectiveRootContainer) {
            effectiveRootContainer = document.body;
            this.#logger.info("No [data-highlight-root] found, using document.body as effective root container for serialization.");
        }

        // The key for this root container is its data-highlight-root value, or a special key for document.body
        const rootContainerKey = effectiveRootContainer.dataset?.highlightRoot || 'document-body';

        const startContainerPath = this.#getNodePath(range.startContainer, effectiveRootContainer);
        const endContainerPath = this.#getNodePath(range.endContainer, effectiveRootContainer);

        if (startContainerPath === null || endContainerPath === null) {
            this.#logger.warn("Could not serialize range: start or end container not found within the determined root container.");
            return null;
        }

        return {
            startContainerPath: startContainerPath,
            startOffset: range.startOffset,
            endContainerPath: endContainerPath,
            endOffset: range.endOffset,
            rootContainerKey: rootContainerKey // Use the data-highlight-root value or 'document-body'
        };
    }

    /**
     * Deserializes a plain object containing path-based range data back into a Range object.
     * It uses the `rootContainerKey` from the serialized data to find the correct root container.
     * If `rootContainerKey` is 'document-body', it defaults to `document.body`.
     * Otherwise, it searches for an element with the corresponding `data-highlight-root` attribute.
     * @private
     * @param {object} serializedRangeData - The serialized range data.
     * @returns {Range|null} The reconstructed Range object, or `null` if reconstruction fails.
     */
    #deserializeRange(serializedRangeData) {
        if (!serializedRangeData || !Array.isArray(serializedRangeData.startContainerPath) || serializedRangeData.startOffset === undefined ||
            !Array.isArray(serializedRangeData.endContainerPath) || serializedRangeData.endOffset === undefined ||
            !serializedRangeData.rootContainerKey === undefined) { // Ensure rootContainerKey is present
            this.#logger.error("Invalid serialized range data provided for deserialization.");
            return null;
        }

        let targetRootContainer = null;
        if (serializedRangeData.rootContainerKey === 'document-body') {
            targetRootContainer = document.body;
        } else {
            // Find the element with the matching data-highlight-root attribute
            targetRootContainer = document.querySelector(`[data-highlight-root="${serializedRangeData.rootContainerKey}"]`);
        }

        if (!targetRootContainer) {
            this.#logger.warn(`Failed to find target root container with data-highlight-root="${serializedRangeData.rootContainerKey}" for deserialization.`);
            return null;
        }

        const startNode = this.#getNodeFromPath(serializedRangeData.startContainerPath, targetRootContainer);
        const endNode = this.#getNodeFromPath(serializedRangeData.endContainerPath, targetRootContainer);

        if (!startNode || !endNode) {
            this.#logger.warn("Failed to reconstruct range: start or end node not found from path within the deserialized root container.");
            return null;
        }

        try {
            const range = new Range();
            range.setStart(startNode, serializedRangeData.startOffset);
            range.setEnd(endNode, serializedRangeData.endOffset);
            return range;
        } catch (e) {
            this.#logger.error("Error reconstructing range from serialized data:", e);
            return null;
        }
    }

    /**
     * Converts an underline style string (e.g., 'solid') to a CSS text-decoration value.
     * @private
     * @param {string} underlineStyle - The underline style ('solid', 'dashed', 'dotted', 'none').
     * @returns {string} The CSS text-decoration value.
     */
    #getUnderlineCssValue(underlineStyle) {
        if (underlineStyle === 'none' || !underlineStyle) {
            return 'none';
        }
        return `underline ${underlineStyle}`;
    }
