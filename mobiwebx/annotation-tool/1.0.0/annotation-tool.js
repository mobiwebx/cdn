        if (!this.#underlineOptionsMenu || !this.#underlineDropdownButton) return;

        const isShowing = this.#underlineOptionsMenu.classList.toggle('show');

        if (isShowing) {
            this.#underlineDropdownButton.classList.add('open');
            const buttonRect = this.#underlineDropdownButton.getBoundingClientRect();
            const menuContainerRect = this.#menuContainerElement.getBoundingClientRect();
            const underlineOptionsRect = this.#underlineOptionsMenu.getBoundingClientRect();

            let top = buttonRect.bottom - menuContainerRect.top + 5;
            let left = buttonRect.left - menuContainerRect.left + (buttonRect.width / 2) - (underlineOptionsRect.width / 2);

            this.#underlineOptionsMenu.style.top = `${top}px`;
            this.#underlineOptionsMenu.style.left = `${left}px`;
            this.#logger.debug(`Underline dropdown shown at (relative to main menu): T=${top.toFixed(1)}px, L=${left.toFixed(1)}px`);
        } else {
            this.#underlineDropdownButton.classList.remove('open');
            this.#logger.info("Underline dropdown hidden.");
        }
