    /**
    * Finds all scrollable and resizable ancestor containers for a given element
    * and adds scroll/resize listeners to them.
    * @private
    * @param {Element} element - The element whose ancestors to check.
    * @returns {void}
    */
    #addScrollAndResizeListeners(element) {
        this.#removeScrollAndResizeListeners(); // Ensure old listeners are removed

        let currentElement = element;
        while (currentElement && currentElement !== document.body && currentElement !== document.documentElement) {
            const style = window.getComputedStyle(currentElement);

            // Check for scrollable containers
            if (style.overflowY === 'auto' || style.overflowY === 'scroll' ||
                style.overflowX === 'auto' || style.overflowX === 'scroll') {
                currentElement.addEventListener('scroll', this.#boundHandleContainerScrollOrResize);
                this.#watchedContainers.push(currentElement);
                this.#logger.debug(`Listening for scroll on:`, currentElement);
            }

            // Check for resizable containers (more complex, using MutationObserver might be better for size changes)
            // For simpler cases, we can listen for `resize` on window and `scroll` on parent for layout changes
            // For actual element resize, `ResizeObserver` is ideal, but for simplicity here we rely on window resize
            // and scroll events. A comprehensive solution would integrate ResizeObserver.

            currentElement = currentElement.parentElement;
        }

        // Always listen to the window and document for global changes
        window.addEventListener('resize', this.#boundHandleContainerScrollOrResize);
        document.addEventListener('scroll', this.#boundHandleContainerScrollOrResize); // For body/document scroll
        this.#watchedContainers.push(window);
        this.#watchedContainers.push(document); // Represents document scrolling

        this.#logger.debug(`Added listeners to ${this.#watchedContainers.length} containers.`);
    }

    /**
     * Removes all scroll and resize listeners added by _addScrollAndResizeListeners.
     * @private
     * @returns {void}
     */
    #removeScrollAndResizeListeners() {
        this.#watchedContainers.forEach(container => {
            if (container === window) {
                window.removeEventListener('resize', this.#boundHandleContainerScrollOrResize);
            } else if (container === document) {
                document.removeEventListener('scroll', this.#boundHandleContainerScrollOrResize);
            } else {
                container.removeEventListener('scroll', this.#boundHandleContainerScrollOrResize);
                // If you added other event types (like resize), remove them here too
            }
        });
        this.#watchedContainers = [];
        this.#logger.debug("Removed all scroll and resize listeners.");
    }

    /**
     * Handles global pointerdown events to manage the visibility of the underline dropdown and context menu.
     * @private
     * @param {Event} event - The pointerdown event triggered globally.
     * The method checks if the click event occurs outside the visible underline dropdown menu and its trigger button.
     * If so, it toggles the dropdown menu's visibility, likely hiding it.
     * Additionally, it checks if the click is outside the context menu component itself. If true, it hides the context menu.
     * * Note: The method allows both the dropdown and context menu to potentially hide on the same click, though prioritization
     * can be implemented if needed by altering the logic within.
     * @returns {void}
     */
    #handleGlobalPointerDown(event) {
        const path = event.composedPath();

        // --- Logic for dismissing the underline dropdown ---
        if (this.#underlineOptionsMenu && this.#underlineOptionsMenu.classList.contains('show')) {
            // If the click is outside the dropdown menu AND outside its trigger button
            if (!path.includes(this.#underlineOptionsMenu) && !path.includes(this.#underlineDropdownButton)) {
                this.#toggleUnderlineOptions(); // This likely hides the dropdown
                // Important: If the dropdown is dismissed, and this component itself might be listening for
                // clicks outside to hide, we might want to prevent the context menu hiding in this same click.
                // However, given the original separation, it's safer to let the context menu hide if it also
                // meets its criteria. This means the context menu might hide *after* the dropdown.
                // If you want to prioritize dropdown dismissal and prevent context menu hiding on the same click,
                // you'd add a 'return' here or a flag. For now, we allow both to potentially happen.
            }
        }

        // --- Logic for hiding the context menu (this component) ---
        // This assumes 'this' refers to the context menu component.
        if (!path.includes(this)) {
            this.hide(); // This hides the context menu
            this.#logger.info("Context menu hidden (clicked outside).");
        }
    }

    /**
     * Handler for scroll and resize events on watched containers. Hides the menu.
     * @private
     * @param {Event} event - The scroll or resize event.
     * @returns {void}
     */
    #handleContainerScrollOrResize(event) {
        this.#logger.info("Container scrolled or resized, hiding menu.");
        this.hide();
    }
