    /**
     * Helper method to synchronize boolean properties and attributes.
     * @param {string} propName - The name of the property (e.g., 'checked', 'disabled').
     * @param {string} attrName - The name of the corresponding attribute (e.g., 'checked', 'disabled').
     * @param {any} value - The new value to set.
     * @returns {boolean} True if the property actually changed, false otherwise.
     */
    #syncBooleanProperty(propName, attrName, value) {
        if (typeof value !== 'boolean') {
            this.#logger.warn(`Invalid value provided for ${propName}. Expected a boolean.`);
        }

        const privatePropName = `_${propName}`;
        const booleanValue = Boolean(value);

        // 1. Change Detection
        if (this[privatePropName] === booleanValue) {
            return false;
        }

        // 2. Update Internal State
        this[privatePropName] = booleanValue;

        // 3. Reflect to Attribute
        if (booleanValue) {
            this.setAttribute(attrName, '');
        } else {
            this.removeAttribute(attrName);
        }
        return true;
    }
