/**
 * @class Logger
 * @description A customizable logging class for JavaScript.
 * It allows enabling/disabling logging, filtering messages by severity level,
 * and provides both global and instance-specific control over logging behavior.
 */
class Logger {
    /**
     * @private
     * @static
     * @type {Object.<string, number>}
     * @description A static map defining the hierarchy and numerical severity of log levels.
     * Higher numbers indicate higher severity.
     */
    static #levelMap = {
        'trace': 0,
        'debug': 1,
        'info': 2,
        'warn': 3, // Changed from 4
        'error': 4, // Changed from 5
    };

    /**
     * @private
     * @static
     * @type {Array<string>}
     * @description A static array of valid log level names, derived directly from the levelMap keys.
     */
    static #possibleLevels = Object.keys(Logger.#levelMap);

    /**
     * @private
     * @static
     * @type {string}
     * @description The globally configured minimum log level name. New Logger instances will
     * default to this level if no instance-specific minimum level is provided.
     */
    static #globalMinimumLevelName = 'warn'; // Default global minimum level

    /**
     * @private
     * @static
     * @type {number}
     * @description The numerical value corresponding to the globally set minimum log level.
     */
    static #globalMinimumLevelValue = Logger.#levelMap[Logger.#globalMinimumLevelName];

    /**
     * Sets the global minimum log level for all Logger instances that don't specify their own.
     * Changes made here will affect subsequently created instances and existing instances
     * that rely on the global default.
     * @param {('trace'|'debug'|'info'|'warn'|'error')} levelName - The desired global minimum level.
     * @returns {void}
     */
    static setGlobalMinimumLevel(levelName) {
        if (Logger.#levelMap[levelName] !== undefined) {
            Logger.#globalMinimumLevelName = levelName;
            Logger.#globalMinimumLevelValue = Logger.#levelMap[levelName];
            console.log(`[Logger] Global minimum log level set to: ${levelName}`);
        } else {
            console.warn(`[Logger] Invalid global log level: '${levelName}'. Keeping current global level: '${Logger.#globalMinimumLevelName}'.`);
        }
    }

    /**
     * Retrieves the current global minimum log level name.
     * @returns {('trace'|'debug'|'info'|'warn'|'error')}
     */
    static getGlobalMinimumLevel() {
        return Logger.#globalMinimumLevelName;
    }

    /**
     * @private
     * @type {boolean}
     * @description Controls whether logging is currently enabled or disabled for this specific instance.
     */
    #loggingEnabled;

    /**
     * @private
     * @type {string}
     * @description The prefix to add to all log messages generated by this instance.
     */
    #logPrefix;

    /**
     * @private
     * @type {string}
     * @description The minimum log level for this particular instance. Messages with lower
     * severity than this level will not be printed.
     */
    #minimumLogLevel;

    /**
     * Creates a new Logger instance.
     * @param {string} [name='Logger'] - A friendly name for this logger instance, used in the log prefix.
     * @param {boolean} [enabled=true] - The initial enabled state of this logger. If `false`, no messages will be logged by this instance.
     * @param {('trace'|'debug'|'info'|'warn'|'error')} [minimumLevel] - The minimum log level for this specific instance. If omitted, it defaults to the global minimum level.
     */
    constructor(name = 'Logger', enabled = true, minimumLevel) {
        this.#loggingEnabled = enabled;
        this.#logPrefix = `[${name}]`;

        // Determine the instance's minimum log level
        if (minimumLevel !== undefined && Logger.#levelMap[minimumLevel] !== undefined) {
            this.#minimumLogLevel = minimumLevel;
        } else {
            // Fallback to global minimum level if no valid instance-specific level is provided
            this.#minimumLogLevel = Logger.#globalMinimumLevelName;
            if (minimumLevel !== undefined) { // Only warn if an invalid level was explicitly passed
                console.warn(`${this.#logPrefix} Invalid minimum level '${minimumLevel}' provided. Falling back to global minimum level: '${this.#minimumLogLevel}'.`);
            }
        }

        // if (enabled) {
        //     console.log(`${this.#logPrefix} Logger initialized and enabled (min level: ${this.#minimumLogLevel}).`);
        // } else {
        //     console.log(`${this.#logPrefix} Logger initialized and disabled.`);
        // }
    }

    /**
     * Enables this logger instance. Log messages will now be printed to the console,
     * subject to this instance's minimum log level.
     * @returns {void}
     */
    enable() {
        this.#loggingEnabled = true;
        console.log(`${this.#logPrefix} Logger enabled.`);
    }

    /**
     * Disables this logger instance. No log messages will be printed by this instance
     * until it is re-enabled.
     * @returns {void}
     */
    disable() {
        this.#loggingEnabled = false;
        console.log(`${this.#logPrefix} Logger disabled.`);
    }

    /**
     * Checks if this logger instance is currently enabled.
     * @returns {boolean} `true` if the logger is enabled, `false` otherwise.
     */
    isEnabled() {
        return this.#loggingEnabled;
    }

    /**
     * The core logging utility method. It only logs messages if this instance is enabled
     * and the message's level is at or above the instance's configured `minimumLogLevel`.
     * @private
     * @param {('trace'|'debug'|'info'|'warn'|'error')} level - The console log level to use for output.
     * @param {...*} messages - The messages or data to log.
     * @returns {void}
     */
    #logInternal(level, ...messages) {
        // First check: Is the logger instance enabled?
        if (!this.#loggingEnabled) {
            return;
        }

        // Second check: Is the message's severity level high enough for this instance?
        const currentLevelValue = Logger.#levelMap[level];
        const minimumLevelValue = Logger.#levelMap[this.#minimumLogLevel];

        if (currentLevelValue < minimumLevelValue) {
            return; // Do not log if the message's level is below the minimum required.
        }

        const output = [this.#logPrefix, ...messages];

        // Output to the console using the specified method, or fallback to `console.log`.
        if (console[level] && typeof console[level] === 'function') {
            console[level](...output);
        } else {
            // Fallback for 'log' level if it was removed, or other unknown levels
            console.log(...output);
        }
    }

    /**
     * Logs a trace message. Useful for fine-grained debugging, showing execution flow.
     * @param {...*} messages - The messages or data to log.
     * @returns {void}
     */
    trace(...messages) {
        this.#logInternal('trace', ...messages);
    }

    /**
     * Logs a debug message. Provides detailed information for debugging purposes.
     * @param {...*} messages - The messages or data to log.
     * @returns {void}
     */
    debug(...messages) {
        this.#logInternal('debug', ...messages);
    }

    /**
     * Logs an informational message. General application flow, important events.
     * @param {...*} messages - The messages or data to log.
     * @returns {void}
     */
    info(...messages) {
        this.#logInternal('info', ...messages);
    }

    /**
     * Logs a warning message. Indicates potential issues or non-critical errors.
     * @param {...*} messages - The messages or data to log.
     * @returns {void}
     */
    warn(...messages) {
        this.#logInternal('warn', ...messages);
    }

    /**
     * Logs an error message. Indicates a significant problem that needs attention.
     * @param {...*} messages - The messages or data to log.
     * @returns {void}
     */
    error(...messages) {
        this.#logInternal('error', ...messages);
    }
}

